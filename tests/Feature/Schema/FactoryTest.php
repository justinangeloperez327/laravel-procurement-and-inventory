it('creates a valid record from the factory', function (string $model) {
    $class = 'App\\Models\\'.$model;
    $record = $class::factory()->create();

    expect($record->exists)->toBeTrue()
        ->and($class::query()->whereKey($record->getKey())->exists())->toBeTrue();
})->with('models');

it('keeps generated parent records in one agency', function () {
    $pr = PurchaseRequest::factory()->create();

    expect($pr->department->agency_id)->toBe($pr->agency_id)
        ->and($pr->fiscalYear->agency_id)->toBe($pr->agency_id)
        ->and($pr->requestedBy->agency_id)->toBe($pr->agency_id);
});
